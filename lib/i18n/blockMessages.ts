/**
 * Translated block labels.
 *
 * The site chrome has been translated into seven languages for a while, but
 * every block label was a hardcoded English string — so a Spanish child got
 * Spanish navigation wrapped around an English programming language. That is
 * the half that matters: the blocks are what a child actually reads while
 * learning.
 *
 * Pure and dependency-free (relative import only) so bare `tsc` can test it.
 *
 * Rules for anyone adding a language:
 *
 * - **Placeholders are load-bearing.** `%1`, `%2`, `%%` map to the block's
 *   inputs by position. Dropping one breaks the block; reordering them
 *   reorders the inputs, which is sometimes exactly what a language needs
 *   (Japanese puts the value before the verb) and is allowed. A test asserts
 *   the multiset of placeholders is preserved.
 * - **Follow the vocabulary a child already meets.** Where Scratch has an
 *   established translation for a concept, use it — a child learning "repetir"
 *   at school should not meet a synonym here.
 * - English is not in this table; it lives in the definitions themselves and
 *   is the fallback for any key a locale has not translated yet.
 */

